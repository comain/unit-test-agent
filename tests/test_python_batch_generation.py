def test_public_python_batch_api_preserves_quality_mode(tmp_path, monkeypatch):
    captured = {}
    target = TargetRef(
        language="python",
        target_id="pkg/router.py",
        display_name="pkg/router.py",
    )

    def capture_request(self, request):
        captured["request"] = request
        from uta.language.python.generation import PythonBatchGenerationResult

        return PythonBatchGenerationResult(results={})

    monkeypatch.setattr(PythonBatchGenerator, "run", capture_request)

    run_python_batch_generation(
        repo_path=tmp_path,
        targets=[target],
        quality_mode="ci_incremental",
    )

    assert captured["request"].quality_mode == "ci_incremental"


