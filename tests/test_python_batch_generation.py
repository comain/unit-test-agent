def test_python_batch_generator_owns_one_standalone_prompt_scope(monkeypatch, tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    runner_home = tmp_path / "runner"
    monkeypatch.setenv("UTA_RUNNER_HOME", str(runner_home))
    request = BatchGenerationRequest.from_targets(
        language="python",
        repo_path=repo,
        targets=[],
    )
    observed = {}

    class ScopeObservingWorkflow:
        def invoke(self, state):
            scope = state["backend_context"]["prompt_artifact_scope"]
            first = scope.durable_directory(
                unit_id="unit-1",
                operation_id="operation-1",
            )
            second = scope.durable_directory(
                unit_id="unit-2",
                operation_id="operation-2",
            )
            observed.update(
                scope=scope,
                first=first,
                second=second,
                run_ids=(scope.run_id, scope.run_id),
            )
            return {**state, "results": {}, "finished": True}

    result = PythonBatchGenerator(workflow_app=ScopeObservingWorkflow()).run(request)

    scope = observed["scope"]
    assert result.final_state["finished"] is True
    assert scope.managed is True
    assert scope.ephemeral_root is not None
    assert observed["run_ids"][0] == observed["run_ids"][1]
    assert scope.run_id in observed["first"].parts
    assert scope.run_id in observed["second"].parts
    assert not Path(scope.ephemeral_root).exists()


def test_python_existing_test_discovery_rejects_broad_content_only_tests(tmp_path):
    repo = tmp_path / "repo"
    source = repo / "chat_robot" / "service" / "fine_tuning_service.py"
    source.parent.mkdir(parents=True)
    source.write_text("def dispatch_fine_tuning_run(run):\n    return run\n", encoding="utf-8")
    pure = repo / "tests" / "test_fine_tuning_pure.py"
    pure.parent.mkdir(parents=True)
    pure.write_text(
        "MODULE = 'chat_robot/service/fine_tuning_service.py'\n"
        "def test_fine_tuning_service_helpers_work_without_django_runtime():\n"
        "    assert MODULE\n",
        encoding="utf-8",
    )
    control = repo / "chat_robot" / "test" / "test_fine_tuning_control_plane.py"
    control.parent.mkdir(parents=True)
    control.write_text(
        "from chat_robot.service import fine_tuning_service\n"
        "def test_control_plane():\n"
        "    assert fine_tuning_service\n",
        encoding="utf-8",
    )
    target = default_registry().adapter_for("python").normalize_target(
        RawTargetSelection(target="chat_robot/service/fine_tuning_service.py")
    )

    matches = discover_strict_python_test_candidates(
        repo,
        target,
        context_payload={"symbols": [{"name": "dispatch_fine_tuning_run"}]},
    )

    assert matches == []
    assert select_python_test_destination(repo, target, context_payload={}).path == (
        "tests/uta_generated/test_chat_robot_service_fine_tuning_service.py"
    )


