def _verify_generated_test(
    repo: Path,
    target: TargetRef,
    generated_abs: Path,
    *,
    context_payload: Dict[str, Any],
    verification_runner: Optional[Callable[..., PythonVerificationResult]],
    coverage_gate: float,
    mutation_gate: float,
    changed_lines: Optional[Dict[str, List[int]]] = None,
) -> PythonVerificationResult:
    syntax_version = (context_payload.get("syntax") or {}).get("version") or "python3"
    try:
        registry = VerificationRunnerRegistry(
            (PythonVerificationRunner(verification_runner or verify_python_target),)
        )
        runner = registry.runner_for("python")
        return runner.verify(
            repo,
            target,
            test_paths=[generated_abs.relative_to(repo).as_posix()],
            syntax_version=syntax_version,
            coverage_gate=coverage_gate,
            mutation_gate=mutation_gate,
            changed_lines=changed_lines,
        )
    except Exception as exc:
        return PythonVerificationResult(
            status="failed",
            reason_code="verification_error",
            message=str(exc),
        )


def _changed_lines_from_task_context(manager: Any, task_id: int) -> Optional[Dict[str, List[int]]]:
    task = manager.get_task(task_id)
    if not task:
        return None
    context = json_loads(task.get("ci_context_json") or "{}")
    enforcement = context.get("enforcement") if isinstance(context, dict) else None
    evidence = enforcement.get("evidence") if isinstance(enforcement, dict) else None
    changed = evidence.get("changedLines") or evidence.get("changed_lines") if isinstance(evidence, dict) else None
    if not isinstance(changed, dict):
        return None
    normalized: Dict[str, List[int]] = {}
    for path, lines in changed.items():
        if not path:
            continue
        normalized[str(path)] = sorted({int(line) for line in lines or [] if int(line) > 0})
    return normalized or None


