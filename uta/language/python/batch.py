def _format_side_effect_hints(items: Iterable[Dict[str, Any]]) -> List[str]:
    hints = []
    for item in items:
        kind = item.get("kind") or "side_effect"
        line = item.get("line")
        detail = item.get("detail") or ""
        hints.append(f"{kind} line {line}: {detail}" if line else f"{kind}: {detail}")
    return hints


def _format_changed_line_hints(
    target: TargetRef,
    changed_lines: Optional[Dict[str, List[int]]],
    context_payload: Dict[str, Any],
) -> List[str]:
    if not changed_lines:
        return []
    source_path = target.source_path or _source_path_from_target(target.target_id)
    target_lines = set(changed_lines.get(source_path) or changed_lines.get(source_path.replace("\\", "/")) or [])
    if not target_lines:
        return []
    symbols = context_payload.get("symbols") or []
    hints: List[str] = []
    for line_number in sorted(target_lines):
        symbol_name = _symbol_for_line(symbols, line_number)
        if symbol_name:
            hints.append(f"{source_path}:{line_number} in `{symbol_name}`")
        else:
            hints.append(f"{source_path}:{line_number}")
    return hints


def _symbol_for_line(symbols: Iterable[Dict[str, Any]], line_number: int) -> Optional[str]:
    best_name = None
    best_line = -1
    for symbol in symbols or []:
        start = int(symbol.get("line") or symbol.get("start_line") or 0)
        end = int(symbol.get("end_line") or start or 0)
        if start <= line_number <= end and start >= best_line:
            best_name = str(symbol.get("name") or symbol.get("symbol") or "")
            best_line = start
    return best_name or None


def _event_error_message(event: Dict[str, Any]) -> str:
    error = event.get("error") if isinstance(event, dict) else {}
    data = error.get("data") if isinstance(error, dict) else {}
    return str((data or {}).get("message") or event.get("reason") or "Python generation failed")


def _empty_token_bucket() -> Dict[str, int]:
    return {"input": 0, "output": 0, "reasoning": 0, "cache_read": 0, "cache_write": 0, "total": 0}


def _empty_session_token_usage() -> Dict[str, Any]:
    return {
        "main_model_tokens": _empty_token_bucket(),
        "small_model_tokens": _empty_token_bucket(),
        "other_model_tokens": _empty_token_bucket(),
        "total_tokens": _empty_token_bucket(),
    }


def _merge_bucket(dest: Dict[str, int], src: Dict[str, Any]) -> None:
    for key in ("input", "output", "reasoning", "cache_read", "cache_write", "total"):
        dest[key] = int(dest.get(key, 0) or 0) + int(src.get(key, 0) or 0)


def _merge_session_token_usage(dest: Dict[str, Any], src: Dict[str, Any]) -> None:
    for bucket_name in ("main_model_tokens", "small_model_tokens", "other_model_tokens", "total_tokens"):
        _merge_bucket(dest.setdefault(bucket_name, _empty_token_bucket()), src.get(bucket_name) or {})


def _safe_analyze_tokens(client: Any, session_id: str) -> Dict[str, Any]:
    analyzer = getattr(client, "analyze_session_tokens", None)
    if not callable(analyzer):
        return _empty_session_token_usage()
    try:
        return analyzer(session_id) or _empty_session_token_usage()
    except Exception:
        return _empty_session_token_usage()


def _safe_analyze_retrospect(client: Any, session_id: str) -> Dict[str, Any]:
    analyzer = getattr(client, "analyze_session_retrospect", None)
    if not callable(analyzer):
        return {}
    try:
        return analyzer(session_id) or {}
    except Exception:
        return {}
